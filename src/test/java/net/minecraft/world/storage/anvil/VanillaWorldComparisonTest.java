package net.minecraft.world.storage.anvil;

import net.minecraft.block.Block;
import net.minecraft.block.BlockRegistry;
import net.minecraft.client.resources.ClasspathResourceManager;
import net.minecraft.nbt.NbtIo;
import net.minecraft.nbt.NbtTag;
import net.minecraft.world.World;
import net.minecraft.world.biome.BiomeRegistry;
import net.minecraft.world.chunk.Chunk;
import org.junit.jupiter.api.Assumptions;
import org.junit.jupiter.api.Test;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * Differential check against a world generated by the real 1.8.9 server
 * (master context §82): reads its Anvil region files and compares vanilla's
 * own data with ours. Skipped unless a vanilla world is available — set
 * {@code -Dlegacycraft.vanillaWorld=<path to the world folder>} or leave the
 * default below pointing at one.
 */
class VanillaWorldComparisonTest {
    private static final Path WORLD = Path.of(System.getProperty("legacycraft.vanillaWorld", "C:/Server/world"));
    private final BlockRegistry blocks = BlockRegistry.load(new ClasspathResourceManager());
    private final BiomeRegistry biomes = BiomeRegistry.load(new ClasspathResourceManager(), blocks);

    private void requireWorld() {
        Assumptions.assumeTrue(Files.isDirectory(WORLD.resolve("region")),
            "No vanilla 1.8.9 world at " + WORLD + " — skipping the differential comparison");
    }

    @Test
    void readsTheWorldMetadata() throws IOException {
        requireWorld();
        NbtTag.Compound level = NbtIo.readCompressed(WORLD.resolve("level.dat")).getCompound("Data");
        System.out.println("Vanilla world: name=" + level.getString("LevelName")
            + " generator=" + level.getString("generatorName") + " seed=" + level.getLong("RandomSeed")
            + " spawn=" + level.getInt("SpawnX") + "," + level.getInt("SpawnY") + "," + level.getInt("SpawnZ"));
        assertEquals(19133, level.getInt("version"), "Anvil format version");
    }

    @Test
    void everyBlockIdAndBiomeIdInTheWorldIsKnown() throws IOException {
        requireWorld();
        Map<Integer, Long> unknownBlocks = new TreeMap<>(), biomeCounts = new TreeMap<>();
        long total = 0;
        for (Path file : regionFiles()) {
            RegionFile region = RegionFile.open(file);
            for (int cx = 0; cx < RegionFile.CHUNKS; cx++) {
                for (int cz = 0; cz < RegionFile.CHUNKS; cz++) {
                    NbtTag.Compound root = region.readChunk(region.regionX() * 32 + cx, region.regionZ() * 32 + cz);
                    if (root == null) continue;
                    var imported = AnvilChunkReader.read(root, 0);
                    for (int x = 0; x < Chunk.SIZE; x++) {
                        for (int z = 0; z < Chunk.SIZE; z++) {
                            biomeCounts.merge(imported.biome(x, z), 1L, Long::sum);
                            for (int y = 0; y < Chunk.HEIGHT; y++) {
                                int id = imported.chunk().get(x, y, z) >>> 4;
                                total++;
                                if (id >= blocks.size()) unknownBlocks.merge(id, 1L, Long::sum);
                            }
                        }
                    }
                }
            }
        }
        System.out.println("Scanned " + total + " blocks; biome IDs present: " + biomeCounts.keySet());
        for (int id : biomeCounts.keySet())
            assertTrue(biomes.byId(id) != null, "biome ID " + id + " (" + biomeCounts.get(id) + " columns) is missing from our table");
        assertTrue(unknownBlocks.isEmpty(), "block IDs outside our table: " + unknownBlocks);
    }

    @Test
    void ourLightEngineAgreesWithTheLightVanillaStored() throws IOException {
        requireWorld();
        // Import two rings of neighbours (light reaches 15 blocks, a chunk is 16 wide) and relight the middle one.
        Path file = WORLD.resolve("region/r.0.0.mca");
        Assumptions.assumeTrue(Files.exists(file), "no region r.0.0");
        RegionFile region = RegionFile.open(file);
        // Only chunks whose eight neighbours were generated too can be relit exactly.
        boolean[][] present = new boolean[RegionFile.CHUNKS][RegionFile.CHUNKS];
        boolean[][] lit = new boolean[RegionFile.CHUNKS][RegionFile.CHUNKS];
        for (int cx = 0; cx < RegionFile.CHUNKS; cx++) {
            for (int cz = 0; cz < RegionFile.CHUNKS; cz++) {
                NbtTag.Compound root = region.readChunk(cx, cz);
                present[cx][cz] = root != null;
                // Only chunks vanilla finished lighting (LightPopulated) have final light to compare against.
                lit[cx][cz] = root != null && AnvilChunkReader.read(root, 0).lit();
            }
        }
        List<int[]> centres = new ArrayList<>();
        for (int cx = 2; cx < RegionFile.CHUNKS - 2 && centres.size() < 4; cx += 2) {
            for (int cz = 2; cz < RegionFile.CHUNKS - 2 && centres.size() < 4; cz += 2) {
                boolean all = lit[cx][cz];
                for (int dx = -2; dx <= 2; dx++) for (int dz = -2; dz <= 2; dz++) all &= present[cx + dx][cz + dz];
                if (all) centres.add(new int[]{cx, cz});
            }
        }
        Assumptions.assumeFalse(centres.isEmpty(), "no fully surrounded chunk in this region");
        System.out.println("lit chunks in region: " + java.util.Arrays.stream(lit).mapToInt(row -> { int n = 0; for (boolean b : row) if (b) n++; return n; }).sum());
        System.out.println("comparing light in chunks " + centres.stream().map(c -> c[0] + "," + c[1]).toList());
        long sky = 0, skyMatch = 0, block = 0, blockMatch = 0;
        int[] skyDelta = new int[31], blockDelta = new int[31];
        List<String> examples = new ArrayList<>();
        for (int[] centreChunk : centres) {
            int centreX = centreChunk[0], centreZ = centreChunk[1];
            World world = new World(blocks, biomes, 0L);
            Map<Long, AnvilChunkReader.Imported> imported = new HashMap<>();
            for (int cx = centreX - 2; cx <= centreX + 2; cx++) {
                for (int cz = centreZ - 2; cz <= centreZ + 2; cz++) {
                    NbtTag.Compound root = region.readChunk(cx, cz);
                    Assumptions.assumeTrue(root != null, "chunk " + cx + "," + cz + " was never generated");
                    var chunk = AnvilChunkReader.read(root, imported.size());
                    imported.put((long) cx << 32 | (cz & 0xffffffffL), chunk);
                    world.restoreChunk(chunk.chunk());
                }
            }
            var centre = imported.get((long) centreX << 32 | (centreZ & 0xffffffffL));
            for (int x = 0; x < Chunk.SIZE; x++) {
                for (int z = 0; z < Chunk.SIZE; z++) {
                    for (int y = 0; y < Chunk.HEIGHT; y++) {
                        int worldX = centreX * Chunk.SIZE + x, worldZ = centreZ * Chunk.SIZE + z;
                        int ourSky = world.getSkyLight(worldX, y, worldZ), theirSky = centre.vanillaSkyLight(x, y, z);
                        int ourBlock = world.getBlockLight(worldX, y, worldZ), theirBlock = centre.vanillaBlockLight(x, y, z);
                        sky++;
                        if (ourSky == theirSky) skyMatch++;
                        else {
                            skyDelta[ourSky - theirSky + 15]++;
                            if (examples.size() < 12) examples.add("sky at " + worldX + "," + y + "," + worldZ
                                + " ours=" + ourSky + " vanilla=" + theirSky
                                + " block=" + world.getState(worldX, y, worldZ).block().name().path()
                                + " above=" + world.getState(worldX, y + 1, worldZ).block().name().path());
                        }
                        block++;
                        if (ourBlock == theirBlock) blockMatch++;
                        else {
                            blockDelta[ourBlock - theirBlock + 15]++;
                            if (examples.size() < 12) examples.add("block at " + worldX + "," + y + "," + worldZ
                                + " ours=" + ourBlock + " vanilla=" + theirBlock
                                + " block=" + world.getState(worldX, y, worldZ).block().name().path());
                        }
                    }
                }
            }
        }
        System.out.printf("sky light agreement %.4f%% (%d/%d), block light %.4f%% (%d/%d)%n",
            100.0 * skyMatch / sky, skyMatch, sky, 100.0 * blockMatch / block, blockMatch, block);
        for (int i = 0; i < 31; i++) {
            if (skyDelta[i] > 0) System.out.println("  sky light off by " + (i - 15) + " in " + skyDelta[i] + " blocks");
            if (blockDelta[i] > 0) System.out.println("  block light off by " + (i - 15) + " in " + blockDelta[i] + " blocks");
        }
        examples.forEach(e -> System.out.println("  " + e));
        assertEquals(sky, skyMatch, "sky light must match the light vanilla 1.8.9 stored");
        // Vanilla leaves a little stale block light behind where sources were removed during
        // generation (its relighting is incremental and known to be imperfect); ours is exact.
        assertTrue(blockMatch >= block - block / 10000,
            "block light differs from vanilla in more than 0.01% of blocks: " + (block - blockMatch) + " of " + block);
    }

    private Iterable<Path> regionFiles() throws IOException {
        try (var files = Files.list(WORLD.resolve("region"))) {
            return files.filter(p -> p.getFileName().toString().endsWith(".mca")).toList();
        }
    }
}
